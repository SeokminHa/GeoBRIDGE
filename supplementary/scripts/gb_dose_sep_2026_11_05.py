def all_tasks():
    L = []
    for c in NEW:
        for g in GRNS:
            for t in TOPOS:
                for s in SIMS: L.append(("gen", f"gen_{g}_{t}_{c}_{s}", g, t, c, s))
    for m in ("velo",) + GPU_EXT + CPU_EXT:
        for c in NEW:
            for g in GRNS:
                for t in TOPOS:
                    for s in SIMS: L.append((m, f"velo_{g}_{t}_{c}_{s}" if m == "velo" else f"ext_{m}_{g}_{t}_{c}_{s}", g, t, c, s))
